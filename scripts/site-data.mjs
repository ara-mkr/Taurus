// Writes apps/site/data.js from the real connector list, so the website never lists a connection Taurus doesn't have.
// Run: node scripts/site-data.mjs
import { mkdtempSync, writeFileSync, copyFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

process.env.TAURUS_HOME = mkdtempSync(join(tmpdir(), 'taurus-site-'));
const root = fileURLToPath(new URL('..', import.meta.url));
const { connectorDefs } = await import(join(root, 'apps/server/src/connectors.ts'));
const { readers, composioCatalog } = await import(join(root, 'apps/server/src/connectors/composio.ts'));

const labels = { Mail: 'Mail', Calendar: 'Calendar', Chat: 'Chat', Tasks: 'Tasks', Code: 'Code', Files: 'Files', Sales: 'Sales', Money: 'Money', Numbers: 'Numbers', Body: 'Health', Media: 'Music', Feeds: 'Feeds', AI: 'AI', Phone: 'Ringing' };
// Apps Taurus reads. AI providers and the phone services (Twilio, ntfy) are on the Connections page but read nothing.
const native = connectorDefs().filter(d => !['Hub', 'AI', 'Phone'].includes(d.group)).map(d => [d.name, d.reads, labels[d.group], 'Direct']);
const viaComposio = Object.values(readers).map(r => [r.name, `${r.reads}.`, 'Composio', 'Composio']);
writeFileSync(join(root, 'apps/site/data.js'), `// Generated by scripts/site-data.mjs from apps/server. Do not edit by hand.\nwindow.TAURUS_CONNECTIONS = ${JSON.stringify([...native, ...viaComposio])};\nwindow.TAURUS_COMPOSIO_COUNT = ${composioCatalog.length};\n`);
copyFileSync(join(root, 'apps/server/src/connectors/composio-catalog.json'), join(root, 'apps/site/composio-catalog.json'));
console.log(`${native.length} direct, ${viaComposio.length} through Composio, ${composioCatalog.length} in Composio's catalog`);
